def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def P(text, indent=True, jc="both", bold=False):
    """Абзац тела: Times New Roman 14 pt, интервал 1,5 (наследуется из стиля)."""
    rpr = '<w:sz w:val="28"/><w:szCs w:val="28"/>'
    run_rpr = ("<w:b/><w:bCs/>" + rpr) if bold else rpr
    ind = '<w:ind w:firstLine="709"/>' if indent else '<w:ind w:firstLine="0"/>'
    return (
        f"<w:p><w:pPr>{ind}<w:jc w:val=\"{jc}\"/>"
        f"<w:rPr>{rpr}</w:rPr></w:pPr>"
        f"<w:r><w:rPr>{run_rpr}</w:rPr>"
        f'<w:t xml:space="preserve">{esc(text)}</w:t></w:r></w:p>'
    )


def TBL(rows, widths):
    """Таблица с тонкими границами; первая строка — шапка с серой заливкой."""
    total = sum(widths)
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out = [
        f'<w:tbl><w:tblPr><w:tblW w:w="{total}" w:type="dxa"/>'
        '<w:jc w:val="center"/>'
        "<w:tblBorders>"
        '<w:top w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        '<w:left w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        '<w:bottom w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        '<w:right w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        '<w:insideH w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        '<w:insideV w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
        "</w:tblBorders>"
        '<w:tblCellMar><w:left w:w="60" w:type="dxa"/>'
        '<w:right w:w="60" w:type="dxa"/></w:tblCellMar>'
        '<w:tblLook w:val="0000" w:firstRow="0" w:lastRow="0" '
        'w:firstColumn="0" w:lastColumn="0" w:noHBand="0" w:noVBand="0"/>'
        f"</w:tblPr><w:tblGrid>{grid}</w:tblGrid>"
    ]
    for ri, row in enumerate(rows):
        header = ri == 0
        out.append("<w:tr>")
        for ci, cell in enumerate(row):
            shd = (
                '<w:shd w:val="clear" w:color="auto" w:fill="E8E8E8"/>'
                if header
                else ""
            )
            b = "<w:b/><w:bCs/>" if header else ""
            out.append(
                f'<w:tc><w:tcPr><w:tcW w:w="{widths[ci]}" w:type="dxa"/>'
                f"{shd}</w:tcPr>"
                '<w:p><w:pPr><w:jc w:val="center"/>'
                '<w:rPr><w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr></w:pPr>'
                f'<w:r><w:rPr>{b}<w:sz w:val="24"/><w:szCs w:val="24"/></w:rPr>'
                f'<w:t xml:space="preserve">{esc(cell)}</w:t></w:r></w:p></w:tc>'
            )
        out.append("</w:tr>")
    out.append("</w:tbl>")
    return "".join(out)


def TBL_CAPTION(text):
    """Заголовок таблицы — над таблицей, слева, без абзацного отступа."""
    return P(text, indent=False, jc="left")


def FIG_CAPTION(text):
    """Подпись рисунка — под рисунком, по центру."""
    return P(text, indent=False, jc="center")


def FIG_PLACEHOLDER(text):
    """Текстовый плейсхолдер рисунка по центру (как в Главах 1-2 базового файла)."""
    return P(text, indent=False, jc="center")


def block(paragraphs):
    return "".join(paragraphs)


