def find_paragraphs(xml):
    return [(m.start(), m.end(), m.group(0))
            for m in re.finditer(r"<w:p\b.*?</w:p>", xml, re.S)]


def para_text(seg):
    runs = re.findall(r"<w:t(?: [^>]*)?>(.*?)</w:t>", seg)
    return "".join(runs)


def para_style(seg):
    m = re.search(r'<w:pStyle w:val="([^"]*)"', seg)
    return m.group(1) if m else ""


def build():
    work = os.path.join(os.path.dirname(__file__), "_thesis_build")
    if os.path.exists(work):
        shutil.rmtree(work)
    os.makedirs(work)
    with zipfile.ZipFile(BASE) as z:
        names = z.namelist()
        z.extractall(work)

    doc_path = os.path.join(work, "word", "document.xml")
    xml = open(doc_path, encoding="utf-8").read()
    paras = find_paragraphs(xml)

    # Сопоставление: текст заголовка -> вставляемый после него контент.
    insert_after = {
        "3 ПРОГРАММНАЯ РЕАЛИЗАЦИЯ": CH3_INTRO,
        "3.1 Архитектура программного комплекса": S31,
        "3.2 Модуль сбора трейсов": S32,
        "3.3 Модуль решения MDP": S33,
        "3.4 Модуль инференса с JointAdaSpec": S34,
        "3.5 Реализация baseline-методов": S35,
        "3.6 Используемые инструменты и технологии": S36,
        "4 ЭКСПЕРИМЕНТАЛЬНОЕ ИССЛЕДОВАНИЕ": CH4_INTRO,
        "4.1 Методика экспериментов": S41,
        "4.2 Исследуемые пары моделей": S42,
        "4.3 Бенчмарки и метрики": S43,
        "4.4 Результаты сравнения с baseline": S44,
        "4.5 Pareto-анализ «скорость-качество»": S45,
        "4.6 Ablation study": S46,
        "4.7 Анализ пороговой поверхности": S47,
        "4.8 Обсуждение результатов": S48,
    }
    # Замена абзацев-заглушек по точному тексту.
    replace_text = {
        "Основные результаты работы Научная новизна и практическая значимость "
        "Направления дальнейших исследований": CONCLUSION,
        "Вывывы": REFERENCES_BLOCK,
        "Выв": APP_B,
        "Вывы": APP_V,
        "вывы": APP_G,
    }

    edits = []  # (start, end, replacement)
    used_insert = set()
    used_replace = set()
    for start, end, seg in paras:
        txt = para_text(seg).strip()
        if txt in insert_after and txt not in used_insert:
            # вставка после данного заголовка тела
            edits.append((end, end, insert_after[txt]))
            used_insert.add(txt)
        elif txt in replace_text and txt not in used_replace:
            edits.append((start, end, replace_text[txt]))
            used_replace.add(txt)

    missing_i = set(insert_after) - used_insert
    missing_r = set(replace_text) - used_replace
    if missing_i:
        raise SystemExit(f"Не найдены заголовки для вставки: {missing_i}")
    if missing_r:
        raise SystemExit(f"Не найдены заглушки для замены: {missing_r}")

    # Применяем правки справа налево, чтобы смещения не сбивались.
    edits.sort(key=lambda e: e[0], reverse=True)
    for start, end, repl in edits:
        xml = xml[:start] + repl + xml[end:]

    # Обновление счётчиков в реферате (подстановки внутри одиночных run'ов).
    xml = xml.replace("работа N с., 4 ", "работа 96 с., 4 ")
    xml = xml.replace(", N рис., N табл., N источников, 4 приложения.",
                      ", 6 рис., 4 табл., 16 источников, 4 приложения.")

    open(doc_path, "w", encoding="utf-8").write(xml)

    if os.path.exists(OUT):
        os.remove(OUT)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for name in names:
            z.write(os.path.join(work, name), name)

    shutil.rmtree(work)
    print(f"Готово: {OUT}")
    print(f"Вставлено разделов: {len(used_insert)}, заменено заглушек: "
          f"{len(used_replace)}")


if __name__ == "__main__":
    build()
